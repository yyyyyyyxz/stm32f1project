/**
 * 功能: 系统初始化
 * 参数: None
 * 返回: None
 * 说明: None
 */
void System_Init(void)
{
    HAL_Init();                                         /* HAL       Init */
    SystemClock_Config(RCC_PLL_MUL9);                   /* System    Init */
    Delay_Init((uint16_t)(SystemCoreClock / 1000000U)); /* Delays    Init */
}

/**
 * 功能: 设备初始化
 * 参数: None
 * 返回: None
 * 说明: None
 */
void Device_Init(void)
{
		if (DEVICE_LED)
			Led_Init();                           /* LED   Init */
		if (DEVICE_KEY)
			Key_Init();                           /* KEY   Init */
		if (DEVICE_USART)
			Usart_Init(115200);										/* USART Init */
}

